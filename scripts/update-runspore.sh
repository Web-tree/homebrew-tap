#!/bin/sh
# Writes Formula/runspore.rb for a runspore release, after checking the release
# key's signature on SHA256SUMS (the same check as runspore's install.sh).
#
#   scripts/update-runspore.sh            # newest release
#   scripts/update-runspore.sh v0.10.5    # a given tag
#
# Needs: gh, ssh-keygen, awk.
set -eu

REPO='Web-tree/runspore'
NAMESPACE='runspore-release'
RELEASE_KEY='ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIGy3mjvtp10UZgB9Y8u3KNBOh66DHPo3bdbZEszh9b1k runspore-release'

tag=${1:-$(gh release view -R "$REPO" --json tagName -q .tagName)}
version=${tag#v}
root=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

gh release download "$tag" -R "$REPO" -p SHA256SUMS -p SHA256SUMS.sig -D "$tmp"
printf '%s namespaces="%s" %s\n' "$NAMESPACE" "$NAMESPACE" "$RELEASE_KEY" >"$tmp/allowed_signers"
ssh-keygen -Y verify -f "$tmp/allowed_signers" -I "$NAMESPACE" -n "$NAMESPACE" \
	-s "$tmp/SHA256SUMS.sig" <"$tmp/SHA256SUMS" >/dev/null ||
	{ echo "SHA256SUMS of $tag is not signed by the runspore release key" >&2; exit 1; }

sum() {
	awk -v n="spore-$1.tar.gz" '$2 == n { print $1; c++ } END { exit (c != 1) }' "$tmp/SHA256SUMS" ||
		{ echo "SHA256SUMS of $tag has no single line for spore-$1.tar.gz" >&2; exit 1; }
}
mac_arm=$(sum aarch64-apple-darwin)
mac_x86=$(sum x86_64-apple-darwin)
linux_arm=$(sum aarch64-unknown-linux-musl)
linux_x86=$(sum x86_64-unknown-linux-musl)
base="https://github.com/$REPO/releases/download/$tag"

cat >"$root/Formula/runspore.rb" <<EOF
# Generated by scripts/update-runspore.sh from the signed SHA256SUMS of $tag.
class Runspore < Formula
  desc "Run durable workflows from your terminal; installs the spore CLI"
  homepage "https://runspore.com"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/spore-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/spore-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_x86"
    end
  end

  on_linux do
    on_arm do
      url "$base/spore-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/spore-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_x86"
    end
  end

  livecheck do
    url :stable
    strategy :github_latest
  end

  def install
    bin.install "spore"
  end

  test do
    assert_match "spore #{version}", shell_output("#{bin}/spore --version")
  end
end
EOF
echo "Formula/runspore.rb -> $tag"
